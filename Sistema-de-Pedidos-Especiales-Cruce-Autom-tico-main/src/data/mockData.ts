/**
 * Returns the default collaborator and recognized area for a branch.
 * For branches with a single designated team member, returns them immediately.
 * For Villa Lucre, returns null by default to trigger the "¿Quién eres?" identification prompt.
 */
export function getBranchDefaultRecognition(branch: BranchName): {
  collaboratorName: string;
  department: Channel;
  role: string;
  hasMultipleMembers: boolean;
} {
  const branchCollaborators = AUTHORIZED_COLLABORATORS.filter((c) => c.branch === branch);
  if (branch === 'Villa Lucre') {
    return {
      collaboratorName: 'Leidys Perez',
      department: 'Mostrador',
      role: 'Ventas Mostrador',
      hasMultipleMembers: true,
    };
  }

  const primary = branchCollaborators[0];
  if (primary) {
    return {
      collaboratorName: primary.name,
      department: primary.department,
      role: primary.role,
      hasMultipleMembers: false,
    };
  }

  return {
    collaboratorName: 'Asesor de Sucursal',
    department: 'Taller',
    role: 'Asesor Changan',
    hasMultipleMembers: false,
  };
}

/**
 * Returns all collaborators registered for a specific branch.
 */
export function getCollaboratorsForBranch(branch: BranchName): AuthorizedCollaborator[] {
  return AUTHORIZED_COLLABORATORS.filter((c) => c.branch === branch);
}

/**
 * Smart recognition: Finds collaborator and resolves their registered department/channel automatically.
 */
export function recognizeCollaborator(name: string): AuthorizedCollaborator | undefined {
  const clean = name.trim().toLowerCase();
  return AUTHORIZED_COLLABORATORS.find(
    (c) => c.name.toLowerCase() === clean || c.name.toLowerCase().includes(clean)
  );
}

